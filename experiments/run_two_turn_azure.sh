#!/usr/bin/env bash
# Two-turn Azure run: six conditions, eligible seeds, K=10.
#
# Fills the n=1 cells. Every condition currently has exactly one model
# observation; this takes stochastic mode to n=23 or n=30 per condition and
# gives `redirect` its first model data of any kind.
#
# Costed from measured usage (experiments/azure_budget.py):
#   stochastic only, 1 sample   152 instances   ~$8.43
#   stochastic + deterministic  281 instances   ~$15.58
#   stochastic, 3 samples       456 instances   ~$25.28
#
# Two conditions need special handling, both by design rather than by bug:
#   no_change    localization asserts a change occurred, so it is dropped
#   degradation  undefined in deterministic mode (halving p=1 is meaningless)
#
# Usage:
#   export AZURE_OPENAI_API_KEY=...
#   ./run_two_turn_azure.sh sto 1          # stochastic, 1 sample  (~$8)
#   ./run_two_turn_azure.sh both 1         # both modes, 1 sample  (~$16)
#   ./run_two_turn_azure.sh sto 3          # stochastic, 3 samples (~$25)
#
# Resumable: completed artifacts are skipped, so re-running after an
# interruption costs nothing for work already done.

set -uo pipefail

MODES_ARG="${1:-sto}"
SAMPLES="${2:-1}"
DEPLOYMENT="${DEPLOYMENT:-gpt-4o}"
ENDPOINT="${ENDPOINT:-https://YOUR-RESOURCE.openai.azure.com}"
K="${K:-10}"
TAG="${TAG:-twoturn_k${K}}"
OUTDIR="pilot_artifacts/${TAG}"

# The run set is read from runs/seed_eligibility.json, generated by
# experiments/seed_eligibility.py, so the seeds here cannot drift from the
# criteria that justify them.
#
# It is the INTERSECTION across all six conditions, not a per-condition list.
# Matched mode exists so a seed gives the same graph, start, goal and T*
# across conditions; running no_change on 30 seeds and silent_break on 23
# would confound the intervention with the seven extra graphs.
#
#   stochastic    n=23   seeds 1..30 less 2, 3, 6, 14, 15, 24, 27
#   deterministic n=3    seeds 8, 13, 25 at full strictness
#
# Deterministic is n=3 because integer hop costs create equal-cost paths, so
# the uniqueness criterion almost never holds. Relaxing it reaches n=23, but
# that relaxation is a group decision and is not assumed here.
ELIG="runs/seed_eligibility.json"
if [ ! -f "$ELIG" ]; then
  echo "Missing $ELIG. Run: python3 experiments/seed_eligibility.py" >&2
  exit 2
fi

case "$MODES_ARG" in
  sto)  MODES="sto" ;;
  det)  MODES="det" ;;
  both) MODES="sto det" ;;
  *)    echo "usage: $0 [sto|det|both] [samples]"; exit 2 ;;
esac

if [ -z "${AZURE_OPENAI_API_KEY:-}" ]; then
  echo "AZURE_OPENAI_API_KEY is not set. Refusing to start." >&2
  exit 2
fi
if [[ "$ENDPOINT" == *YOUR-RESOURCE* ]]; then
  echo "ENDPOINT is still the placeholder. Set it first." >&2
  exit 2
fi

mkdir -p "$OUTDIR"
LOG="$OUTDIR/run.log"
ok=0; skipped=0; failed=0; consecutive_fail=0

echo "tag=$TAG  model=$DEPLOYMENT  K=$K  modes=$MODES  samples=$SAMPLES"
echo "writing to $OUTDIR" | tee -a "$LOG"

for mode in $MODES; do
  for cond in no_change irrelevant silent_break hard_removal degradation redirect; do

    # degradation halves a success probability, which is undefined when
    # every link is p=1.
    if [ "$cond" = "degradation" ] && [ "$mode" = "det" ]; then continue; fi

    SEEDS=$(python3 -c "import json,sys; d=json.load(open('$ELIG')); print(' '.join(str(x) for x in d['run_set']['$mode']))")
    if [ -z "$SEEDS" ]; then
      echo "  skip $cond/$mode: empty run set" ; continue
    fi

    # localization asks which pair changed, which presupposes one did.
    PROBES=""
    if [ "$cond" = "no_change" ]; then
      PROBES="--probes detection preservation adaptation"
    fi

    for seed in $SEEDS; do
      for s in $(seq 1 "$SAMPLES"); do
        stamp="${cond}_${mode}_s${seed}_r${s}"
        marker="$OUTDIR/$stamp/.done"
        if [ -f "$marker" ]; then
          skipped=$((skipped+1)); continue
        fi

        if python3 -B run_pilot.py \
            --condition "$cond" --seed "$seed" --mode "$mode" \
            --turn-mode two_turn --reelicit \
            --k "$K" --budget "$K" \
            $PROBES \
            --provider azure --model "$DEPLOYMENT" \
            --azure-endpoint "$ENDPOINT" \
            --max-tokens 4096 \
            --out "$OUTDIR/$stamp" >>"$LOG" 2>&1
        then
          touch "$marker"
          ok=$((ok+1)); consecutive_fail=0
          printf "  ok   %-28s (%d done)\n" "$stamp" "$ok"
        else
          failed=$((failed+1)); consecutive_fail=$((consecutive_fail+1))
          printf "  FAIL %-28s (see %s)\n" "$stamp" "$LOG"
          # A run of failures usually means auth, quota or a bad deployment
          # name. Stop rather than spend the budget discovering that 150
          # times.
          if [ "$consecutive_fail" -ge 5 ]; then
            echo "STOPPING: 5 consecutive failures. Check $LOG." >&2
            echo "summary: ok=$ok skipped=$skipped failed=$failed"
            exit 1
          fi
        fi
      done
    done
  done
done

echo
echo "summary: ok=$ok skipped=$skipped failed=$failed"
echo "artifacts in $OUTDIR"
